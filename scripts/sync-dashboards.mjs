#!/usr/bin/env node
// Copies each *.html in dashboards_raw/ to public/analyses/, injecting a
// fixed-position chrome overlay (back-link + AI-generated chip) right after
// the opening <body> tag. Run via `npm run dashboards:sync` or automatically
// on `prebuild`.
//
// Drop new dashboards into dashboards_raw/ untouched; this script bakes in
// the chrome at build time so deep links keep working (the output stays a
// flat static HTML file at /analyses/<name>.html).

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const RAW_DIR = join(ROOT, "dashboards_raw");
const OUT_DIR = join(ROOT, "public", "analyses");

const CHROME_HTML = `<div id="__sps_btn_chrome" style="position:fixed;top:0;right:0;z-index:99999;display:flex;align-items:center;gap:10px;padding:7px 14px;background:rgba(255,255,255,0.94);border:1px solid #ddd;border-top:none;border-right:none;border-bottom-left-radius:8px;box-shadow:0 1px 4px rgba(0,0,0,0.12);font-family:system-ui,-apple-system,sans-serif;font-size:12px;line-height:1;-webkit-backdrop-filter:blur(6px);backdrop-filter:blur(6px)"><a href="/analyses" style="color:#0072B2;text-decoration:none;font-weight:500">&larr; SPS By the Numbers &middot; Analyses</a><span title="AI-generated by Claude (Anthropic). Verify before citing." style="background:#E69F00;color:#1A1714;font-size:10px;font-weight:700;letter-spacing:.08em;padding:3px 7px;border-radius:3px;text-transform:uppercase">AI Generated</span><button type="button" aria-label="Dismiss" title="Dismiss" onclick="this.parentNode.remove()" style="background:transparent;border:none;color:#6b7280;cursor:pointer;font-size:18px;line-height:1;padding:0 2px;margin-left:2px;border-radius:3px" onmouseover="this.style.color='#111';this.style.background='rgba(0,0,0,0.06)'" onmouseout="this.style.color='#6b7280';this.style.background='transparent'">&times;</button></div>`;

// Keep in sync with GA_MEASUREMENT_ID in config/constants.ts.
const GA_MEASUREMENT_ID = "G-WKM5FTSSLL";
const GA_HTML = `<script async src="https://www.googletagmanager.com/gtag/js?id=${GA_MEASUREMENT_ID}"></script>
<script>window.dataLayer=window.dataLayer||[];function gtag(){dataLayer.push(arguments);}gtag('js',new Date());gtag('config','${GA_MEASUREMENT_ID}');</script>`;

const HEAD_OPEN_RE = /<head\b[^>]*>/i;
const BODY_OPEN_RE = /<body\b[^>]*>/i;

function injectAfter(html, regex, snippet, label, sourceFile) {
  const match = html.match(regex);
  if (!match) {
    throw new Error(`No ${label} tag found in ${sourceFile}`);
  }
  const idx = match.index + match[0].length;
  return html.slice(0, idx) + "\n" + snippet + html.slice(idx);
}

function injectChrome(html, sourceFile) {
  let out = injectAfter(html, HEAD_OPEN_RE, GA_HTML, "<head>", sourceFile);
  out = injectAfter(out, BODY_OPEN_RE, CHROME_HTML, "<body>", sourceFile);
  return out;
}

async function main() {
  let entries;
  try {
    entries = await readdir(RAW_DIR, { withFileTypes: true });
  } catch (err) {
    if (err.code === "ENOENT") {
      console.log(`[sync-dashboards] ${relative(ROOT, RAW_DIR)} does not exist; nothing to do.`);
      return;
    }
    throw err;
  }

  await mkdir(OUT_DIR, { recursive: true });

  const htmlFiles = entries.filter(
    (e) => e.isFile() && e.name.toLowerCase().endsWith(".html"),
  );

  if (htmlFiles.length === 0) {
    console.log(`[sync-dashboards] No .html files in ${relative(ROOT, RAW_DIR)}.`);
    return;
  }

  for (const entry of htmlFiles) {
    const srcPath = join(RAW_DIR, entry.name);
    const dstPath = join(OUT_DIR, entry.name);
    const raw = await readFile(srcPath, "utf8");
    const out = injectChrome(raw, entry.name);
    await writeFile(dstPath, out);
    console.log(
      `[sync-dashboards] ${relative(ROOT, srcPath)} -> ${relative(ROOT, dstPath)}`,
    );
  }
}

main().catch((err) => {
  console.error("[sync-dashboards] failed:", err);
  process.exit(1);
});
